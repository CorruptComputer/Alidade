using System.Text;
using System.Text.Json;

namespace Alidade.OsmGen.Generators;

/// <summary>
///   Reads the id-tagging-schema npm package and emits a single
///   <c>TaggingData.g.cs</c> file containing all presets, fields,
///   categories, and deprecation rules as static C# collections.
/// </summary>
internal static class TaggingSchemaGenerator
{
    private static readonly JsonSerializerOptions JsonOpts = new(JsonSerializerDefaults.Web);

    public static void Generate(string nodeModulesDir, string outputDir)
    {
        Console.WriteLine("TaggingSchemaGenerator: reading id-tagging-schema...");

        string schemaDir = Path.Combine(nodeModulesDir, "@openstreetmap", "id-tagging-schema", "dist");

        string presetsJson = File.ReadAllText(Path.Combine(schemaDir, "presets.json"));
        string fieldsJson = File.ReadAllText(Path.Combine(schemaDir, "fields.json"));
        string deprecJson = File.ReadAllText(Path.Combine(schemaDir, "deprecated.json"));
        string categoriesJson = File.ReadAllText(Path.Combine(schemaDir, "preset_categories.json"));

        using JsonDocument presetsDoc = JsonDocument.Parse(presetsJson);
        using JsonDocument fieldsDoc = JsonDocument.Parse(fieldsJson);
        using JsonDocument deprecDoc = JsonDocument.Parse(deprecJson);
        using JsonDocument categoriesDoc = JsonDocument.Parse(categoriesJson);

        Console.WriteLine($"  {presetsDoc.RootElement.EnumerateObject().Count()} presets, " +
                          $"{fieldsDoc.RootElement.EnumerateObject().Count()} fields, " +
                          $"{deprecDoc.RootElement.EnumerateArray().Count()} deprecations, " +
                          $"{categoriesDoc.RootElement.EnumerateObject().Count()} categories");

        StringBuilder sb = new();
        sb.AppendLine(CodeGenHelper.AutoGeneratedHeader);
        sb.AppendLine("using Alidade.Osm.Models.Tagging;");
        sb.AppendLine();
        sb.AppendLine("namespace Alidade.Osm.TaggingSchemas;");
        sb.AppendLine();
        sb.AppendLine("public static partial class TaggingData");
        sb.AppendLine("{");

        EmitPresets(sb, presetsDoc.RootElement);
        sb.AppendLine();

        EmitFields(sb, fieldsDoc.RootElement);
        sb.AppendLine();

        EmitDeprecations(sb, deprecDoc.RootElement);
        sb.AppendLine();

        EmitCategories(sb, categoriesDoc.RootElement);

        sb.AppendLine("}");

        string outPath = Path.Combine(outputDir, "TaggingData.g.cs");
        CodeGenHelper.WriteFile(outPath, sb.ToString());
    }

    private static void EmitPresets(StringBuilder sb, JsonElement root)
    {
        sb.AppendLine("    /// <summary>All presets, keyed by their id-tagging-schema ID.</summary>");
        sb.AppendLine("    public static IReadOnlyDictionary<string, Preset> Presets { get; } =");
        sb.AppendLine("        new Dictionary<string, Preset>");
        sb.AppendLine("        {");

        foreach (JsonProperty prop in root.EnumerateObject())
        {
            string id = prop.Name;
            JsonElement el = prop.Value;

            string icon = CodeGenHelper.StringLiteral(
                el.TryGetProperty("icon", out JsonElement iconEl) ? iconEl.GetString() : null);

            string fields = GetStringArray(el, "fields");
            string moreFields = GetStringArray(el, "moreFields");
            string geometry = GetStringArray(el, "geometry");
            string tags = GetTagsDict(el);
            double matchScore = el.TryGetProperty("matchScore", out JsonElement ms) ? ms.GetDouble() : 1.0;
            string name = CodeGenHelper.StringLiteral(
                el.TryGetProperty("name", out JsonElement nameEl) ? nameEl.GetString() : null);
            string terms = GetStringArray(el, "terms");
            string aliases = GetStringArray(el, "aliases");
            bool searchable = !el.TryGetProperty("searchable", out JsonElement srEl) || srEl.GetBoolean();

            sb.AppendLine($"            [{CodeGenHelper.StringLiteral(id)}] = new Preset(");
            sb.AppendLine($"                Id: {CodeGenHelper.StringLiteral(id)},");
            sb.AppendLine($"                Icon: {icon},");
            sb.AppendLine($"                Fields: {fields},");
            sb.AppendLine($"                MoreFields: {moreFields},");
            sb.AppendLine($"                Geometry: {geometry},");
            sb.AppendLine($"                Tags: {tags},");
            sb.AppendLine($"                MatchScore: {matchScore.ToString("G17", System.Globalization.CultureInfo.InvariantCulture)},");
            sb.AppendLine($"                Name: {name},");
            sb.AppendLine($"                Terms: {terms},");
            sb.AppendLine($"                Aliases: {aliases},");
            sb.AppendLine($"                Searchable: {CodeGenHelper.BoolLiteral(searchable)}),");
        }

        sb.AppendLine("        };");
    }

    private static void EmitFields(StringBuilder sb, JsonElement root)
    {
        sb.AppendLine("    /// <summary>All field definitions, keyed by their id-tagging-schema ID.</summary>");
        sb.AppendLine("    public static IReadOnlyDictionary<string, FieldDef> Fields { get; } =");
        sb.AppendLine("        new Dictionary<string, FieldDef>");
        sb.AppendLine("        {");

        foreach (JsonProperty prop in root.EnumerateObject())
        {
            string id = prop.Name;
            JsonElement el = prop.Value;

            string key = CodeGenHelper.StringLiteral(
                el.TryGetProperty("key", out JsonElement kEl) ? kEl.GetString() ?? id : id);
            string keys = GetStringArray(el, "keys");
            string type = CodeGenHelper.StringLiteral(
                el.TryGetProperty("type", out JsonElement tEl) ? tEl.GetString() ?? "text" : "text");
            string options = GetStringArray(el, "options");
            string minValue = CodeGenHelper.NullableDoubleLiteral(
                el.TryGetProperty("minValue", out JsonElement mnEl) ? mnEl.GetDouble() : null);
            string maxValue = CodeGenHelper.NullableDoubleLiteral(
                el.TryGetProperty("maxValue", out JsonElement mxEl) ? mxEl.GetDouble() : null);
            string urlFormat = CodeGenHelper.StringLiteral(
                el.TryGetProperty("urlFormat", out JsonElement ufEl) ? ufEl.GetString() : null);
            string pattern = CodeGenHelper.StringLiteral(
                el.TryGetProperty("pattern", out JsonElement patEl) ? patEl.GetString() : null);
            bool universal = el.TryGetProperty("universal", out JsonElement uEl) && uEl.GetBoolean();
            string locationSet = GetLocationSet(el);
            string label = CodeGenHelper.StringLiteral(
                el.TryGetProperty("label", out JsonElement lblEl) ? lblEl.GetString() : null);

            sb.AppendLine($"            [{CodeGenHelper.StringLiteral(id)}] = new FieldDef(");
            sb.AppendLine($"                Id: {CodeGenHelper.StringLiteral(id)},");
            sb.AppendLine($"                Key: {key},");
            sb.AppendLine($"                Keys: {keys},");
            sb.AppendLine($"                Type: {type},");
            sb.AppendLine($"                Options: {options},");
            sb.AppendLine($"                MinValue: {minValue},");
            sb.AppendLine($"                MaxValue: {maxValue},");
            sb.AppendLine($"                UrlFormat: {urlFormat},");
            sb.AppendLine($"                Pattern: {pattern},");
            sb.AppendLine($"                Universal: {CodeGenHelper.BoolLiteral(universal)},");
            sb.AppendLine($"                LocationSet: {locationSet},");
            sb.AppendLine($"                Label: {label}),");
        }

        sb.AppendLine("        };");
    }

    private static void EmitDeprecations(StringBuilder sb, JsonElement root)
    {
        sb.AppendLine("    /// <summary>All tag deprecation rules.</summary>");
        sb.AppendLine("    public static IReadOnlyList<DeprecationRule> DeprecationRules { get; } =");
        sb.AppendLine("    [");

        foreach (JsonElement el in root.EnumerateArray())
        {
            string old = GetTagsDictFromElement(el, "old");
            string replace = GetTagsDictFromElement(el, "replace");

            sb.AppendLine($"        new DeprecationRule(");
            sb.AppendLine($"            Old: {old},");
            sb.AppendLine($"            Replace: {replace}),");
        }

        sb.AppendLine("    ];");
    }

    private static void EmitCategories(StringBuilder sb, JsonElement root)
    {
        sb.AppendLine("    /// <summary>All preset categories, keyed by their id-tagging-schema ID.</summary>");
        sb.AppendLine("    public static IReadOnlyDictionary<string, PresetCategory> Categories { get; } =");
        sb.AppendLine("        new Dictionary<string, PresetCategory>");
        sb.AppendLine("        {");

        foreach (JsonProperty prop in root.EnumerateObject())
        {
            string id = prop.Name;
            string icon = CodeGenHelper.StringLiteral(
                prop.Value.TryGetProperty("icon", out JsonElement iconEl) ? iconEl.GetString() : null);
            string members = GetStringArray(prop.Value, "members");

            sb.AppendLine($"            [{CodeGenHelper.StringLiteral(id)}] = new PresetCategory(");
            sb.AppendLine($"                Id: {CodeGenHelper.StringLiteral(id)},");
            sb.AppendLine($"                Icon: {icon},");
            sb.AppendLine($"                Members: {members}),");
        }

        sb.AppendLine("        };");
    }

    #region Helpers

    private static string GetStringArray(JsonElement el, string prop)
    {
        if (!el.TryGetProperty(prop, out JsonElement arr) || arr.ValueKind != JsonValueKind.Array)
        {
            return "[]";
        }
        string[] items = [.. arr.EnumerateArray()
            .Select(e => e.GetString())
            .OfType<string>()];
        return CodeGenHelper.StringArray(items);
    }

    private static string GetTagsDict(JsonElement el)
    {
        if (!el.TryGetProperty("tags", out JsonElement tagsEl) || tagsEl.ValueKind != JsonValueKind.Object)
        {
            return "new Dictionary<string, string>()";
        }
        return CodeGenHelper.StringDictionary(tagsEl.EnumerateObject()
            .Select(p => new KeyValuePair<string, string>(p.Name, p.Value.GetString() ?? "*")));
    }

    private static string GetTagsDictFromElement(JsonElement parent, string prop)
    {
        if (!parent.TryGetProperty(prop, out JsonElement el) || el.ValueKind != JsonValueKind.Object)
        {
            return "new Dictionary<string, string>()";
        }
        return CodeGenHelper.StringDictionary(el.EnumerateObject()
            .Select(p => new KeyValuePair<string, string>(p.Name, p.Value.GetString() ?? "*")));
    }

    private static string GetLocationSet(JsonElement el)
    {
        if (!el.TryGetProperty("locationSet", out JsonElement ls) || ls.ValueKind != JsonValueKind.Object)
        {
            return "null";
        }
        string include = GetStringArray(ls, "include");
        string exclude = GetStringArray(ls, "exclude");
        return $"new LocationSet(Include: {include}, Exclude: {exclude})";
    }
    #endregion
}